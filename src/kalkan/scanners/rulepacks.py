#: The environment variable of the switch.
ENV_VAR = "KALKAN_RULE_PACKS"
#: License groups of the packs: OSI-approved licenses and AGPL-3.0. ADR-0005, Lisans politikası.
OSI_GROUP = "osi"
GROUPS = (OSI_GROUP, "agpl")
#: Packs of earlier versions, with the reason of the removal. ``KALKAN_RULE_PACKS`` ignores them.
