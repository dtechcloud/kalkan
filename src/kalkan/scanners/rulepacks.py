"""The vendored Opengrep rule packs (ENGINE-SPEC 13, ADR-0005 K.8).

Files below ``rules/opengrep-packs`` (:func:`packs_dir`):

- ``curation.json``: written by hand. The packs (name, ``third_party`` component, license
  group, license, metadata filters), the pack priority, the drop groups (each with a kind and a
  reason), the rules that the automatic duplicate check must keep, and class overrides.
- ``index.json``: generated by ``scripts/build_opengrep_packs.py`` from the vendored copies in
  ``third_party/`` and ``curation.json``. Every kept rule with its class and sink patterns, the
  dropped rules with their reason, and per pack the counts.
- ``<pack>/<path>``: generated. Byte copies of the vendored files that hold at least one kept
  rule. A dropped rule inside a kept file is in ``index.json`` ``excluded_rules``; the adapter
  passes it with ``--exclude-rule``.

Rule IDs: Opengrep runs from the packs folder with ``-f <pack>`` and ``--rewrite-rule-ids``, so
it reports a rule as ``<pack>.<folders of the file, joined by dots>.<upstream ID>``
(:func:`full_rule_id`). The IDs are unique across the packs and the same on every machine.

Duplicates: a rule repeats another rule when both have the same kalkan class, a common language
and every sink pattern of the rule is also a sink pattern of the other rule (:func:`repeats`).
The sink patterns are the positive ``pattern`` and ``pattern-regex`` entries of a search rule,
or of the ``pattern-sinks`` of a taint rule, with whitespace and metavariable names normalized
(:func:`sink_patterns`). The build drops a pack rule that repeats a rule of a pack with a higher
priority. The adapter drops, at run time, a pack rule that repeats a rule of kalkan's own pack
``rules/opengrep`` (:func:`kalkan_duplicates`), so a new kalkan rule needs no rebuild.

The switch (:func:`selection`): the environment variable ``KALKAN_RULE_PACKS``: ``all`` (the
default), ``osi`` (only the packs with an OSI-approved license; the AGPL pack stays off),
``none``, or a comma-separated list of pack names. A name in :data:`REMOVED_PACKS` (a pack of
an earlier version) is ignored, so an old setting keeps working.
"""

