_METAVARIABLE = re.compile(r"\$\.\.\.[A-Za-z_][A-Za-z0-9_]*|\$[A-Z_][A-Z0-9_]*")
_SPACES = re.compile(r"\s+")
_PUNCTUATION_SPACE = re.compile(r"\s*([()\[\]{},.;:=<>+*/!&|^%~?-])\s*")
_ARGUMENTS = re.compile(r"\([^()]*\)")


def packs_dir() -> Path:
    """Return the ``rules/opengrep-packs`` folder (:func:`kalkan.resources.rules_dir`)."""
    from kalkan.resources import rules_dir

    return rules_dir("opengrep-packs")


def _read_json(path: Path) -> Any:
    from kalkan.util.safe_io import read_bounded

    try:
        return json.loads(read_bounded(path, _MAX_JSON_BYTES))
    except (OSError, ValueError, KalkanError) as exc:
        raise KalkanError(f"cannot read {path.name}: {exc}") from exc


def load_curation(folder: Path | None = None) -> dict[str, Any]:
    """Return ``curation.json`` of the packs folder."""
    return _read_json((folder or packs_dir()) / CURATION_FILE)


def load_index(folder: Path | None = None) -> dict[str, Any]:
    """Return ``index.json`` of the packs folder."""
    return _read_json((folder or packs_dir()) / INDEX_FILE)


def full_rule_id(pack: str, file: str, upstream_id: str) -> str:
    """Return the rule ID that Opengrep reports with ``--rewrite-rule-ids`` from the packs
    folder: the folders of ``<pack>/<file>`` and the upstream ID, joined by dots."""
    parts = PurePosixPath(pack, file).parent.parts
    return ".".join([*parts, upstream_id])


def language_families(languages: Iterable[object]) -> frozenset[str]:
    """Return the language families of a rule ``languages`` list."""
    families = set()
    for language in languages:
        if isinstance(language, str):
            name = language.strip().lower()
            families.add(_FAMILIES.get(name, name))
    return frozenset(families)


def normalize_pattern(pattern: str, *, collapse: bool = False) -> str:
    """Return a pattern with metavariable names, whitespace and spaces around punctuation
    removed, so that two spellings of the same pattern compare equal.

    ``collapse`` also replaces every argument list with ``(...)``: a taint sink is a call whose
    dangerous argument the taint analysis checks, so ``$CURSOR.execute($QUERY, ...)`` becomes
    ``$X.execute(...)``. A search pattern keeps its arguments, because they hold the condition
    (``Cipher.getInstance("DES")``). A ``regex:`` pattern keeps its text.
    """
    if pattern.startswith("regex:"):
        return pattern
    text = _METAVARIABLE.sub(lambda m: "$..." if m.group(0).startswith("$...") else "$X", pattern)
    text = _SPACES.sub(" ", text).strip()
    text = _PUNCTUATION_SPACE.sub(r"\1", text)
    while collapse:
        # A placeholder without parentheses, so that the outer list collapses next.
        collapsed = _ARGUMENTS.sub("\x00", text)
        if collapsed == text:
            text = text.replace("\x00", "(...)")
            break
        text = collapsed
    return text.rstrip(";")


def _positives(spec: object) -> list[str]:
    """Return the positive patterns of a pattern spec (``pattern``, ``pattern-regex``, and the
    entries of ``pattern-either`` and ``patterns``)."""
    found: list[str] = []
    if isinstance(spec, list):
        for item in spec:
            found += _positives(item)
        return found
    if not isinstance(spec, Mapping):
        return found
    for key, value in spec.items():
        if key == "pattern" and isinstance(value, str):
            found.append(value)
        elif key == "pattern-regex" and isinstance(value, str):
            found.append("regex:" + value)
        elif key in {"pattern-either", "patterns"}:
            found += _positives(value)
    return found


_RESTRICTIONS = {
    "pattern-not": "not",
    "pattern-not-inside": "not-inside",
    "pattern-inside": "inside",
    "pattern-not-regex": "not-regex",
}


def _restrictions(spec: object) -> list[str]:
    """Return the conditions of a pattern spec that narrow its matches, as tagged strings."""
    found: list[str] = []
    if isinstance(spec, list):
        for item in spec:
            found += _restrictions(item)
        return found
    if not isinstance(spec, Mapping):
        return found
    for key, value in spec.items():
        if key in _RESTRICTIONS and isinstance(value, str):
            text = value if key == "pattern-not-regex" else normalize_pattern(value)
            found.append(f"{_RESTRICTIONS[key]}:{text}")
        elif key in {"pattern-either", "patterns"}:
            found += _restrictions(value)
        elif key.startswith("metavariable-") and isinstance(value, Mapping):
            found.append(key + ":" + json.dumps(value, sort_keys=True, default=str))
    return found


def restriction_patterns(rule: Mapping[str, Any]) -> frozenset[str]:
    """Return the conditions that narrow the matches of a search rule (``pattern-not``,
    ``pattern-inside``, ``pattern-not-inside``, ``pattern-not-regex``, ``metavariable-*``).
    A taint rule gives an empty set: its sinks decide (module docstring)."""
    if rule.get("mode") == "taint":
        return frozenset()
    keys = ("pattern", "pattern-regex", "pattern-either", "patterns")
    return frozenset(_restrictions({key: rule[key] for key in keys if key in rule}))


def sink_patterns(rule: Mapping[str, Any]) -> frozenset[str]:
    """Return the normalized sink patterns of a rule (module docstring; taint sinks collapse
    their argument lists, :func:`normalize_pattern`)."""
    taint = rule.get("mode") == "taint"
    if taint:
        spec: object = rule.get("pattern-sinks")
        taint_spec = rule.get("taint")
        if spec is None and isinstance(taint_spec, Mapping):
            spec = taint_spec.get("sinks")
    else:
        keys = ("pattern", "pattern-regex", "pattern-either", "patterns")
        spec = {key: rule[key] for key in keys if key in rule}
    return frozenset(
        normalize_pattern(text, collapse=taint) for text in _positives(spec) if text.strip()
    )


def rule_cwes(rule: Mapping[str, Any]) -> list[str]:
    """Return the normalized CWE IDs of a rule's ``metadata.cwe`` in their order."""
    metadata = rule.get("metadata")
    value = metadata.get("cwe") if isinstance(metadata, Mapping) else None
    items = value if isinstance(value, list) else [value]
    found: list[str] = []
    for item in items:
        cwe = normalize_cwe(item)
        if cwe is not None and cwe not in found:
            found.append(cwe)
    return found


def rule_class(cwes: Iterable[str]) -> str | None:
    """Return the class of the first CWE that maps to a class (CWE metadata first)."""
    for cwe in cwes:
        slug = class_for_cwe(cwe)
        if slug is not None:
            return slug
    return None


@dataclass(frozen=True)
class Signature:
    """What the duplicate check compares (:func:`repeats`)."""

    slug: str
    families: frozenset[str]
    sinks: frozenset[str]
    restrictions: frozenset[str] = frozenset()

    @classmethod
    def of(
        cls, slug: str | None, languages: Iterable[object], rule: Mapping[str, Any]
    ) -> Signature:
        return cls(
            slug or "",
            language_families(languages),
            sink_patterns(rule),
            restriction_patterns(rule),
        )

    @classmethod
    def from_record(cls, record: Mapping[str, Any]) -> Signature:
        """Return the signature of an ``index.json`` rule record."""
        return cls(
            str(record.get("class") or ""),
            language_families(record.get("languages") or []),
            frozenset(record.get("sinks") or []),
            frozenset(record.get("restrictions") or []),
        )


def repeats(candidate: Signature, other: Signature) -> bool:
    """Return True when ``candidate`` repeats ``other``: the same class, a common language
    family, no sink pattern of ``candidate`` that ``other`` lacks, and no condition of
    ``other`` that ``candidate`` lacks (``other`` matches at least what ``candidate``
    matches)."""
    if not candidate.slug or candidate.slug != other.slug or not candidate.sinks:
        return False
    if not candidate.families & other.families:
        return False
    return candidate.sinks <= other.sinks and other.restrictions <= candidate.restrictions


@dataclass(frozen=True)
class KalkanRule:
    """A rule of kalkan's own pack ``rules/opengrep``, for the duplicate check."""

    id: str
    signature: Signature


def kalkan_rules(folder: Path) -> list[KalkanRule]:
    """Return the rules of kalkan's own pack (``*.yaml`` and ``*.yml`` of ``folder``).

    The class is ``metadata.kalkan_class`` when it is a known slug, else the class of the CWE
    metadata. A file that the YAML reader cannot read is skipped.
    """
    found: list[KalkanRule] = []
    for path in sorted([*folder.glob("*.yaml"), *folder.glob("*.yml")]):
        try:
            document = miniyaml.load(path.read_text(encoding="utf-8"))
        except (OSError, UnicodeDecodeError, miniyaml.MiniYamlError):
            continue
        rules = document.get("rules") if isinstance(document, Mapping) else None
        for rule in rules if isinstance(rules, list) else []:
            if not isinstance(rule, Mapping) or not isinstance(rule.get("id"), str):
                continue
            metadata = rule.get("metadata")
            declared = metadata.get("kalkan_class") if isinstance(metadata, Mapping) else None
            slug = declared if declared in SLUGS else rule_class(rule_cwes(rule))
            languages = rule.get("languages")
            languages = languages if isinstance(languages, list) else []
            found.append(KalkanRule(rule["id"], Signature.of(slug, languages, rule)))
    return found


def kalkan_duplicates(
    index_rules: Iterable[Mapping[str, Any]], own: Iterable[KalkanRule]
) -> dict[str, str]:
    """Return {pack rule ID: kalkan rule ID} for the pack rules that repeat a rule of kalkan's
    own pack (:func:`repeats`)."""
    own_list = list(own)
    duplicates: dict[str, str] = {}
    for record in index_rules:
        candidate = Signature.from_record(record)
        for rule in own_list:
            if repeats(candidate, rule.signature):
                duplicates[str(record["id"])] = rule.id
                break
    return duplicates


@dataclass(frozen=True)
class Selection:
    """The packs that the switch turns on (:func:`selection`)."""

    setting: str  # the value as given ("all" when the variable is not set)
    source: str  # "default" or ENV_VAR
    enabled: tuple[str, ...]
    disabled: dict[str, str]  # pack name to the reason
    error: str | None = None


def selection(
    packs: Iterable[Mapping[str, Any]], environ: Mapping[str, str] | None = None
) -> Selection:
    """Return the packs that ``KALKAN_RULE_PACKS`` turns on (module docstring).

    ``packs`` are the pack entries of ``index.json`` (``name``, ``group``). An invalid value
    turns every pack off and names the error.
    """
    env = os.environ if environ is None else environ
    raw = env.get(ENV_VAR, "").strip()
    setting = raw.lower() or "all"
    source = ENV_VAR if raw else "default"
    entries = [(str(pack["name"]), str(pack.get("group") or "")) for pack in packs]
    names = [name for name, _ in entries]
    if setting == "all":
        return Selection(setting, source, tuple(names), {})
    if setting == "none":
        reason = f"{ENV_VAR}=none"
        return Selection(setting, source, (), dict.fromkeys(names, reason))
    if setting == OSI_GROUP:
        enabled = tuple(name for name, group in entries if group == OSI_GROUP)
        disabled = {
            name: f"{ENV_VAR}=osi: the license group {group!r} is turned off"
            for name, group in entries
            if group != OSI_GROUP
        }
        return Selection(setting, source, enabled, disabled)
    listed = [item.strip() for item in raw.split(",") if item.strip()]
    wanted = [item for item in listed if item not in REMOVED_PACKS or item in names]
    unknown = [item for item in wanted if item not in names]
    if unknown or not listed:
        error = (
            f"{ENV_VAR}={raw!r} is not valid: use all, osi, none or pack names ({', '.join(names)})"
        )
        return Selection(raw, source, (), dict.fromkeys(names, error), error)
    enabled = tuple(name for name in names if name in wanted)
    disabled = {name: f"{ENV_VAR}={raw} does not name it" for name in names if name not in wanted}
    return Selection(raw, source, enabled, disabled)
