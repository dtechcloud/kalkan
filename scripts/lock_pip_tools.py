#!/usr/bin/env python3
# SPDX-License-Identifier: MIT
"""Write or check the hashed lock of the pip tools (src/kalkan/tools/pip-tools.lock).

Usage:
    python scripts/lock_pip_tools.py --uv <path to uv> [--exclude-newer YYYY-MM-DD]
    python scripts/lock_pip_tools.py --check

``kalkan tools install`` installs the pip tools of the manifest (checkov, bandit, flawfinder,
gixy-ng) into one venv with ``pip install --require-hashes --only-binary :all: -r <lock>``
(kalkan.tools.install). The lock pins the full dependency closure with the sha256 digest of
every wheel and sdist on PyPI, resolved once for every platform and every Python from 3.11 on
(``uv pip compile --universal``). Before, pip resolved the dependencies of the tools at install
time without any pin or digest (self-audit of 2026-11-13).

Without ``--check`` the script writes the requirement strings of the manifest to a temporary
file, runs uv (network: PyPI) and writes the lock with a header. ``--exclude-newer`` makes the
resolution reproducible (default: today). With ``--check`` it reads only the lock and the
manifest (no network): every pip tool must be pinned at its manifest version and every
requirement must carry at least one ``--hash=sha256:`` digest.
"""

from __future__ import annotations

import argparse
import datetime as _dt
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from kalkan.tools import install as install_mod  # noqa: E402
from kalkan.tools.manifest import load_manifest  # noqa: E402

LOCK = install_mod.PIP_LOCK_PATH
HEADER = """\
# The hashed lock of the pip tools of kalkan (kalkan.tools.install, docs/SECURITY.md).
# Generated by scripts/lock_pip_tools.py with uv {uv_version}, resolution date {date}:
#   uv pip compile --universal --generate-hashes --python-version 3.11 --exclude-newer {date}
# Do not edit. After a version change of a pip tool in manifest.json, run the script again.
"""


def _pip_requirements() -> list[str]:
    manifest = load_manifest()
    return sorted(tool.requirement or "" for tool in manifest.tools.values() if tool.kind == "pip")


def write(uv: str, date: str) -> None:
    requirements = _pip_requirements()
    version = subprocess.run(
        [uv, "--version"], check=True, capture_output=True, text=True
    ).stdout.strip()
    with tempfile.TemporaryDirectory() as folder:
        source = Path(folder) / "tools.in"
        target = Path(folder) / "tools.lock"
        source.write_text("\n".join(requirements) + "\n", encoding="utf-8")
        subprocess.run(
            [
                uv,
                "pip",
                "compile",
                "--universal",
                "--generate-hashes",
                "--python-version",
                "3.11",
                "--no-header",
                "--no-annotate",
                "--exclude-newer",
                date,
                str(source),
                "-o",
                str(target),
            ],
            check=True,
        )
        body = target.read_text(encoding="utf-8")
    header = HEADER.format(uv_version=version.removeprefix("uv ").split()[0], date=date)
    LOCK.write_text(header + body, encoding="utf-8", newline="\n")
    problems = check()
    if problems:
        raise SystemExit("\n".join(problems))
    print(f"wrote {LOCK.relative_to(ROOT).as_posix()} for {', '.join(requirements)}")


def check() -> list[str]:
    try:
        pins = install_mod.read_pip_lock(LOCK)
    except (OSError, ValueError) as exc:
        return [f"{LOCK.name}: {exc}"]
    problems = []
    for requirement in _pip_requirements():
        name, version = install_mod.requirement_pin(requirement)
        if version not in pins.get(name, set()):
            problems.append(f"{LOCK.name} does not pin {name}=={version}; run the script again")
    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="check the lock (no network)")
    parser.add_argument("--uv", help="path to the uv program (to write the lock)")
    parser.add_argument("--exclude-newer", default=_dt.date.today().isoformat())
    args = parser.parse_args(argv)
    if args.check:
        problems = check()
        for problem in problems:
            print(problem, file=sys.stderr)
        if not problems:
            print(f"{LOCK.name}: ok")
        return 1 if problems else 0
    if not args.uv:
        parser.error("--uv is required to write the lock")
    write(args.uv, args.exclude_newer)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
