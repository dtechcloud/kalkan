# Generators


def _markdown_note(source: str) -> str:
    return (
        f"<!-- {GENERATED_MARK} from {source}. Do not edit this file. "
        f"Edit {source}, then run: python scripts/sync_host_files.py -->"
    )


def build_runbook(root: Path) -> str:
    """Return `AGENTS.md`, derived from `CLAUDE.md`."""
    text = _read(root / CLAUDE_RUNBOOK)
    body = apply_replacements(text, RUNBOOK_REPLACEMENTS, CLAUDE_RUNBOOK)
    return _markdown_note(CLAUDE_RUNBOOK) + "\n\n" + body.rstrip("\n") + "\n"


def build_skill(root: Path) -> str:
    """Return the Codex orchestrator skill, derived from the Claude Code `/kalkan` skill."""
    fields, body = parse_front_matter(_read(root / CLAUDE_SKILL), CLAUDE_SKILL)
    for key in ("name", "description"):
        if not fields.get(key):
            raise SyncError(f"{CLAUDE_SKILL}: the front matter has no {key!r}")
    description = apply_replacements(
        fields["description"], DESCRIPTION_REPLACEMENTS, f"{CLAUDE_SKILL} (description)"
    )
    body = apply_replacements(body, SKILL_REPLACEMENTS, CLAUDE_SKILL)
    return (
        "---\n"
        f"name: {fields['name']}\n"
        f"description: {_yaml_string(description + SKILL_DESCRIPTION_SUFFIX)}\n"
        "---\n\n"
        f"{_markdown_note(CLAUDE_SKILL)}\n\n"
        f"{body.rstrip(chr(10))}\n"
    )


def build_skill_policy(root: Path) -> str:
    """Return the Codex `agents/openai.yaml` of the skill.

    The Claude key `disable-model-invocation: true` becomes `allow_implicit_invocation: false`:
    Codex then starts the skill only on an explicit `$kalkan` mention.
    """
    fields, _ = parse_front_matter(_read(root / CLAUDE_SKILL), CLAUDE_SKILL)
    value = fields.get("disable-model-invocation", "false").strip().lower()
    if value not in ("true", "false"):
        raise SyncError(f"{CLAUDE_SKILL}: disable-model-invocation must be true or false")
    implicit = "false" if value == "true" else "true"
    return (
        f"# {GENERATED_MARK} from {CLAUDE_SKILL} (disable-model-invocation).\n"
        "# Do not edit this file. Edit the Claude Code skill, then run:\n"
        "# python scripts/sync_host_files.py\n"
        "policy:\n"
        f"  allow_implicit_invocation: {implicit}\n"
    )


def codex_host_notes(tools: Sequence[str]) -> str:
    """Return the Codex section of a subagent's instructions.

    Claude Code limits a subagent to a tool list. Codex has no tool list: it gives the subagent
    a shell and a file editing tool inside the sandbox of the parent session. The notes state
    the Claude limits as Codex rules.
    """
    lines = [
        "## Codex host notes",
        "",
        "These notes map the rules above to OpenAI Codex. The rules above still hold.",
        "",
    ]
    if "Grep" in tools or "Glob" in tools:
        lines.append(
            "- Codex has no Read, Grep or Glob tool. Read, list and search files only with "
            "read-only shell commands, for example `rg`, `rg --files`, `cat`, `sed -n`, "
            "`Get-Content`, `Select-String` or `Get-ChildItem`."
        )
    else:
        lines.append(
            "- Codex has no Read tool. Read the prompt file with one read-only shell command, "
            "for example `cat` or `Get-Content`. Do not list, search or read other files."
        )
    if "Write" in tools:
        lines.append(
            "- Write the result file with the file editing tool (`apply_patch`). Never write, "
            "move or delete any other file, and never write a file with a shell command."
        )
    lines.extend(
        [
            "- The prompt file can say that you have no shell. Under Codex this means: use the "
            "shell only for the reading that these notes allow. Never run target code, the "
            "kalkan engine, build or test tools, package managers, interpreters, `git`, or a "
            "command that uses the network or changes a file.",
            "- Never read `.env` or `.env.*` files.",
            "- Never start other agents. Never ask for escalated permissions, network access or "
            "web search.",
        ]
    )
    return "\n".join(lines) + "\n"


def build_agent(source_path: Path, source: str) -> tuple[str, str]:
    """Return ``(name, toml_text)`` of the Codex custom agent for one Claude Code subagent."""
    fields, body = parse_front_matter(_read(source_path), source)
    name = fields.get("name", "")
    if name != source_path.stem:
        raise SyncError(f"{source}: the front matter name {name!r} must be {source_path.stem!r}")
    if not fields.get("description"):
        raise SyncError(f"{source}: the front matter has no 'description'")
    tools = _split_list(fields.get("tools", ""))
    description = apply_replacements(
        fields["description"], DESCRIPTION_REPLACEMENTS, f"{source} (description)"
    )
    body = apply_replacements(body, AGENT_BODY_REPLACEMENTS, source).rstrip("\n")
    instructions = body + "\n\n" + codex_host_notes(tools)
    limits = []
    if tools:
        limits.append(f"tools = {', '.join(tools)}")
    if fields.get("maxTurns"):
        limits.append(f"maxTurns = {fields['maxTurns']}")
    header = [
        f"# {GENERATED_MARK} from {source}. Do not edit this file.",
        "# Edit the Claude Code file, then run: python scripts/sync_host_files.py",
        "#",
        "# Codex custom agent. The parent session sets the sandbox, the approval policy and the",
        "# network (.codex/config.toml). A custom agent file cannot change them.",
    ]
    if limits:
        header.append(f"# Claude Code limits without a Codex setting: {'; '.join(limits)}.")
    features = "\n".join(f"{key} = false" for key in AGENT_FEATURES_OFF)
    text = (
        "\n".join(header)
        + "\n\n"
        + f"name = {_toml_string(name)}\n"
        + f"description = {_toml_string(description)}\n"
        + f"developer_instructions = {toml_multiline(instructions)}\n"
        + "\n[features]\n"
        + features
        + "\n"
    )
    parsed = tomllib.loads(text)
    if (
        parsed.get("name") != name
        or parsed.get("description") != description
        or parsed.get("developer_instructions") != instructions
    ):
        raise SyncError(f"{source}: the generated TOML does not round-trip")
    return name, text


def _insert_note(text: str, note: str, source: str) -> str:
    """Return ``text`` with ``note`` as the first body line after the front matter."""
    if not text.startswith("---\n"):
        raise SyncError(f"{source}: the file has no front matter")
    end = text.find("\n---\n", 4)
    if end < 0:
        raise SyncError(f"{source}: the front matter has no closing '---' line")
    head = text[: end + len("\n---\n")]
    body = text[end + len("\n---\n") :].lstrip("\n")
    return f"{head}\n{note}\n\n{body.rstrip(chr(10))}\n"


def build_plugin_skill(root: Path) -> str:
    """Return the plugin orchestrator skill, derived from the Claude Code `/kalkan` skill."""
    text = _read(root / CLAUDE_SKILL)
    parse_front_matter(text, CLAUDE_SKILL)  # checks the shape
    text = apply_replacements(text, PLUGIN_SKILL_REPLACEMENTS, CLAUDE_SKILL)
    return _insert_note(text, _markdown_note(CLAUDE_SKILL), CLAUDE_SKILL)


def build_plugin_agent(source_path: Path, source: str) -> tuple[str, str]:
    """Return ``(name, markdown)`` of the plugin agent for one Claude Code subagent."""
    text = _read(source_path)
    fields, _ = parse_front_matter(text, source)
    name = fields.get("name", "")
    if name != source_path.stem:
        raise SyncError(f"{source}: the front matter name {name!r} must be {source_path.stem!r}")
    for key in ("hooks", "mcpServers", "permissionMode"):
        if key in fields:
            raise SyncError(f"{source}: a plugin agent ignores the front matter key {key!r}")
    text = apply_replacements(text, PLUGIN_AGENT_REPLACEMENTS, source)
    return name, _insert_note(text, _markdown_note(source), source)


def _claude_agent_files(root: Path) -> list[Path]:
    return sorted((root / CLAUDE_AGENTS).glob(f"{AGENT_GLOB}.md"))


def expected_files(root: Path) -> dict[str, str]:
    """Return the generated files as ``{relative POSIX path: content}``."""
    agents = _claude_agent_files(root)
    if not agents:
        raise SyncError(f"{CLAUDE_AGENTS}: no {AGENT_GLOB}.md files")
    files = {
        CODEX_RUNBOOK: build_runbook(root),
        CODEX_SKILL: build_skill(root),
        CODEX_SKILL_POLICY: build_skill_policy(root),
    }
    files[PLUGIN_SKILL] = build_plugin_skill(root)
    for path in agents:
        source = path.relative_to(root).as_posix()
        name, text = build_agent(path, source)
        files[f"{CODEX_AGENTS}/{name}.toml"] = text
        name, text = build_plugin_agent(path, source)
        files[f"{PLUGIN_AGENTS}/{name}.md"] = text
    return files


def _stale_files(root: Path, expected: dict[str, str]) -> list[str]:
    """Return the generated agent files that no Claude agent produces any more."""
    stale = []
    for folder, suffix in ((CODEX_AGENTS, ".toml"), (PLUGIN_AGENTS, ".md")):
        for path in sorted((root / folder).glob(f"{AGENT_GLOB}{suffix}")):
            relative = path.relative_to(root).as_posix()
            if relative not in expected:
                stale.append(relative)
    return stale


def _is_generated(path: Path) -> bool:
    try:
        return GENERATED_MARK in path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return False


def check(root: Path = ROOT) -> list[str]:
    """Return one message per missing, stale or extra generated file. An empty list means in
    sync."""
    expected = expected_files(root)
    problems = []
    for relative, content in expected.items():
        path = root / relative
        if not path.is_file():
            problems.append(f"{relative}: missing")
            continue
        if path.read_text(encoding="utf-8").replace("\r\n", "\n") != content:
            problems.append(f"{relative}: differs from its Claude Code source")
    for relative in _stale_files(root, expected):
        problems.append(f"{relative}: no Claude Code agent produces this file")
    return problems


def write(root: Path = ROOT) -> list[str]:
    """Write the generated files. Remove stale generated agent files. Return the changed paths.

    A stale agent file without the generated mark is a hand-written file: the script keeps it
    and raises :class:`SyncError`.
    """
    expected = expected_files(root)
    changed = []
    for relative, content in expected.items():
        path = root / relative
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current == content:
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        with path.open("w", encoding="utf-8", newline="\n") as handle:
            handle.write(content)
        changed.append(relative)
    for relative in _stale_files(root, expected):
        path = root / relative
        if not _is_generated(path):
            raise SyncError(
                f"{relative}: no Claude Code agent produces this file, and it is not generated. "
                "Remove it or add the matching .claude/agents file."
            )
        path.unlink()
        changed.append(f"{relative} (removed)")
    return changed


def main(argv: Sequence[str] | None = None) -> int:
    """Command-line entry point. Return the exit code."""
    parser = argparse.ArgumentParser(
        description="Generate the OpenAI Codex host files from the Claude Code host files."
    )
    parser.add_argument(
        "--check", action="store_true", help="report drift and exit 1; write nothing"
    )
    parser.add_argument("--root", type=Path, default=ROOT, help=argparse.SUPPRESS)
    args = parser.parse_args(argv)
    root = args.root.resolve()
    try:
        if args.check:
            problems = check(root)
            for problem in problems:
                print(f"drift: {problem}", file=sys.stderr)
            if problems:
                print(
                    "The generated files are out of date. Run: python scripts/sync_host_files.py",
                    file=sys.stderr,
                )
                return 1
            print("The generated host files are in sync.", file=sys.stderr)
            return 0
        changed = write(root)
    except SyncError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    for relative in changed:
        print(f"wrote {relative}", file=sys.stderr)
    if not changed:
        print("The generated host files are already in sync.", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
