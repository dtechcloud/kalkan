# Text helpers


def _read(path: Path) -> str:
    try:
        text = path.read_text(encoding="utf-8")
    except FileNotFoundError as exc:
        raise SyncError(f"{path.as_posix()}: the source file does not exist") from exc
    return text.replace("\r\n", "\n")


def apply_replacements(text: str, replacements: Sequence[Replacement], source: str) -> str:
    """Return ``text`` with the replacements applied in order.

    Raises :class:`SyncError` when a replacement does not occur the stated number of times.
    """
    for number, item in enumerate(replacements, start=1):
        if item.regex:
            pattern = re.compile(item.old)
            found = len(pattern.findall(text))
        else:
            found = text.count(item.old)
        if item.count == "+":
            ok = found >= 1
        elif item.count == "*":
            ok = True
        else:
            ok = found == item.count
        if not ok:
            expected = "at least 1" if item.count == "+" else str(item.count)
            snippet = item.old if len(item.old) <= 80 else item.old[:77] + "..."
            raise SyncError(
                f"{source}: replacement {number} expects {expected} occurrence(s) of "
                f"{snippet!r} and found {found}. The Claude file changed: update the "
                "replacement table in scripts/sync_host_files.py, then run the script again."
            )
        if item.regex:
            text = re.sub(item.old, lambda _match, new=item.new: new, text)
        else:
            text = text.replace(item.old, item.new)
    return text


def parse_front_matter(text: str, source: str) -> tuple[dict[str, str], str]:
    """Split a Markdown file into its front matter (``key: value`` lines) and its body."""
    if not text.startswith("---\n"):
        raise SyncError(f"{source}: the file has no front matter")
    end = text.find("\n---\n", 4)
    if end < 0:
        raise SyncError(f"{source}: the front matter has no closing '---' line")
    fields: dict[str, str] = {}
    for line in text[4:end].splitlines():
        if not line.strip():
            continue
        key, sep, value = line.partition(":")
        if not sep or not key.strip():
            raise SyncError(f"{source}: front matter line {line!r} is not 'key: value'")
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] == '"':
            value = json.loads(value)
        fields[key.strip()] = value
    return fields, text[end + len("\n---\n") :].lstrip("\n")


def _yaml_string(value: str) -> str:
    # A JSON string is a valid YAML double-quoted scalar.
    return json.dumps(value, ensure_ascii=False)


def _toml_string(value: str) -> str:
    # A JSON string is a valid TOML basic string (same escapes; UTF-8 stays raw).
    return json.dumps(value, ensure_ascii=False)


_TOML_LITERAL_FORBIDDEN = re.compile(r"[\x00-\x08\x0b-\x1f\x7f]|'''")


def toml_multiline(value: str) -> str:
    """Return ``value`` as a TOML string, multi-line literal when the text allows it."""
    if _TOML_LITERAL_FORBIDDEN.search(value) or value.endswith("'"):
        return _toml_string(value)
    return "'''\n" + value + "'''"


def _split_list(value: str) -> list[str]:
    return [item.strip() for item in value.split(",") if item.strip()]


