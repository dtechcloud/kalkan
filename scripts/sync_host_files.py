class SyncError(Exception):
    """A source file cannot be converted. The message names the file and the cause."""


@dataclass(frozen=True)
class Replacement:
    """Replace ``old`` with ``new``.

    ``count`` is the number of times that ``old`` must occur: an integer for an exact number,
    ``"+"`` for one or more, ``"*"`` for any number. With ``regex``, ``old`` is a regular
    expression and ``new`` is literal text.
    """

    old: str
    new: str
    count: int | str = 1
    regex: bool = False


