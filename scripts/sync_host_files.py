"""Generate the OpenAI Codex host files and the Claude Code plugin files from the Claude Code
host files.

kalkan runs under two agent hosts, and Claude Code also loads it as a plugin. The Claude Code
files of the checkout are the source, and this script derives the other files from them, so
that the hosts never drift apart:

| Source (Claude Code)              | Generated                                                 |
|-----------------------------------|-----------------------------------------------------------|
| `CLAUDE.md`                       | `AGENTS.md` (Codex)                                       |
| `.claude/skills/kalkan/SKILL.md`  | `.agents/skills/kalkan/SKILL.md` (Codex)                  |
| `disable-model-invocation` key    | `.agents/skills/kalkan/agents/openai.yaml` (Codex)        |
| `.claude/agents/kalkan-<role>.md` | `.codex/agents/kalkan-<role>.toml` (Codex)                |
| `.claude/skills/kalkan/SKILL.md`  | `plugins/kalkan/skills/kalkan/SKILL.md` (plugin)          |
| `.claude/agents/kalkan-<role>.md` | `plugins/kalkan/agents/kalkan-<role>.md` (plugin)         |

The plugin skill runs the engine from the plugin data folder (`${CLAUDE_PLUGIN_DATA}`) and
starts the plugin agents (`kalkan:kalkan-<role>`). `scripts/build_plugin.py` writes the other
plugin files (manifests and the engine wheel).

Usage (from the repository root):

    python scripts/sync_host_files.py           write the generated files
    python scripts/sync_host_files.py --check   exit 1 when a generated file is missing, stale or
                                                extra

**Host-specific text.** An ordered list of replacements changes the Claude-specific text.
Each replacement states how often its source text must occur. When an edit of a Claude file
breaks a replacement, the script stops and names that replacement: update the table in this
file, then run the script again. Shared text that no replacement touches goes to Codex
unchanged. The subagent bodies have no replacement: they are host-neutral, and the script adds
a generated "Codex host notes" section to each one.

`.codex/config.toml`, `.codex/rules/kalkan.rules` and `docs/CODEX.md` are written by hand. This
script does not touch them.
"""

